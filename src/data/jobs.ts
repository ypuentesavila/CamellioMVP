export function getJobById(id: string): Job | undefined {
  return jobs.find((j) => j.id === id);
}

export function getJobsByEmployer(employerId: string): Job[] {
  return jobs.filter((j) => j.employerId === employerId);
}

export function getOpenJobs(): Job[] {
  return jobs.filter((j) => j.status === "open");
}

export function getJobsByCategory(category: string): Job[] {
  return jobs.filter((j) => j.category === category);
}
